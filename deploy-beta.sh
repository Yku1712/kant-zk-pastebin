#!/usr/bin/env bash
set -euo pipefail

# deploy-beta.sh - Deploy beta site to nginx on port 8081
# This script builds kant-pastebin and updates the beta nginx config.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
PASTEBIN_DIR="${PASTEBIN_DIR:-$SCRIPT_DIR}"
BETA_PORT=8081
DOMAIN="${PASTEBIN_DOMAIN:-solana.solfunmeme.com}"

log() {
    echo "[$(date -u +%Y-%m-%dT%H:%M:%SZ)] $1"
}

section() {
    printf '\n=== %s ===\n' "$1"
}

# Get git commit info
get_git_version() {
    local commit=""
    local short_commit=""
    
    if git rev-parse HEAD >/dev/null 2>&1; then
        commit=$(git rev-parse HEAD)
        short_commit=$(git rev-parse --short HEAD)
    fi
    
    local tag=""
    if git describe --tags --exact-match >/dev/null 2>&1; then
        tag=$(git describe --tags)
    fi
    
    echo "${tag:-v0.2.0} (${short_commit:-$(echo "$commit" | cut -c1-7)})"
}

# Set build-time environment variables
export GIT_COMMIT=$(git rev-parse HEAD 2>/dev/null || echo "unknown")
export BUILD_TIME=$(date -u +%Y-%m-%dT%H:%M:%SZ)

section "Git Version Info"
log "Commit: $GIT_COMMIT"
log "Build time: $BUILD_TIME"
log "Version: $(get_git_version)"

section "Building kant-pastebin"
cd "$PASTEBIN_DIR"

# Build using the makefile (nix develop -> cargo build --release)
log "Building release binary with nix develop..."
make dev

log "Build complete: target/release/kant-pastebin"

section "Generating nginx config for beta"
mkdir -p "$PASTEBIN_DIR/nginx-beta"

cat > "$PASTEBIN_DIR/nginx-beta/pastebin-beta.conf" << 'NGINX_CONF'
# Kant Pastebin Beta Site — /pastebin/beta/
# Generated by deploy-beta.sh
# Do not edit manually — regenerate via the deploy script

location /pastebin/beta/ {
    proxy_pass http://127.0.0.1:8081/;
    proxy_http_version 1.1;
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
    
    # Beta site headers - show version info
    add_header X-Pastebin-Beta-Version "v0.2.0";
    add_header X-Pastebin-Beta-Commit "AUTOGENERATED";
    
    client_max_body_size 0;
    proxy_read_timeout 3600s;
    proxy_send_timeout 3600s;
    proxy_connect_timeout 3600s;
    proxy_buffering off;
    proxy_request_buffering off;
    charset utf-8;
}
NGINX_CONF

# Update the commit in the config
sed -i "s/AUTOGENERATED/$GIT_COMMIT/" "$PASTEBIN_DIR/nginx-beta/pastebin-beta.conf"

log "Generated: $PASTEBIN_DIR/nginx-beta/pastebin-beta.conf"

section "Generating systemd service for beta"

cat > "$PASTEBIN_DIR/kant-pastebin-beta.service" << SERVICE_EOF
[Unit]
Description=Kant Pastebin Beta (version $(get_git_version))
After=network.target

[Service]
Type=simple
WorkingDirectory=$PASTEBIN_DIR
ExecStart=$PASTEBIN_DIR/target/release/kant-pastebin
Restart=always
RestartSec=10
Environment="BIND_ADDR=127.0.0.1:$BETA_PORT"
Environment="UUCP_SPOOL=/mnt/data1/spool/uucp/pastebin"
Environment="BASE_PATH=/pastebin"
Environment="BASE_URL=https://${DOMAIN}"
Environment="NFT_DIR=/mnt/data1/time-2026/03-march/13/nft_enriched"
Environment="ENRICH_PIPELINE=/mnt/data1/time-2026/03-march/09/mmgroup-rust/enrich-qid.sh"
Environment="RUST_LOG=info"
Environment="GIT_COMMIT=$GIT_COMMIT"
Environment="BUILD_TIME=$BUILD_TIME"
Environment="PORT=$BETA_PORT"
TimeoutStartSec=0
TimeoutStopSec=0
NoNewPrivileges=true
PrivateTmp=true
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true

[Install]
WantedBy=default.target
SERVICE_EOF

log "Generated: $PASTEBIN_DIR/kant-pastebin-beta.service"

section "Deployment Summary"
log "Version: $(get_git_version)"
log "Git commit: $GIT_COMMIT"
log "Beta port: $BETA_PORT"
log "Build binary: $PASTEBIN_DIR/target/release/kant-pastebin"
log "Nginx config: $PASTEBIN_DIR/nginx-beta/pastebin-beta.conf"
log "Service file: $PASTEBIN_DIR/kant-pastebin-beta.service"

section "Next steps"
echo "  1. Copy nginx-beta/pastebin-beta.conf to /etc/nginx/conf.d/ or include it in nginx config"
echo "  2. Install kant-pastebin-beta.service to systemd (e.g., systemctl link)"
echo "  3. Start beta service: systemctl start kant-pastebin-beta"
echo "  4. Test beta: curl http://127.0.0.1:$BETA_PORT/ or https://$DOMAIN/pastebin/beta/"
echo "  5. Check version: curl http://127.0.0.1:$BETA_PORT/api/version"

log "Beta deployment ready!"
log "Run 'curl http://127.0.0.1:$BETA_PORT/api/version' to verify version info is displayed."